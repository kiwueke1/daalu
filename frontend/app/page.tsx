"use client";

import { useQuery } from "@tanstack/react-query";
import {
  Activity,
  AlertTriangle,
  Bot,
  FileText,
  Workflow,
} from "lucide-react";
import { GreetingHero } from "@/components/greeting-hero";
import { HeroBriefing } from "@/components/hero-briefing";
import { SummaryTile } from "@/components/cards/summary-tile";
import { api } from "@/lib/api";

/**
 * Home dashboard.
 *
 * Composition:
 *   1. Cinematic hero with the AI core PNG occupying the right edge.
 *   2. The current daily briefing, in full. The operator should not have
 *      to click through to read it — it's the headline of the page.
 *   3. A grid of summary tiles — one bite-sized signal per tile,
 *      each linking through to its detail page. Notifications + the
 *      AI assistant live in the right rail, not here.
 */
export default function HomePage() {
  const { data: alerts, isLoading: alertsLoading } = useQuery({
    queryKey: ["alerts", "all"],
    queryFn: () => api.alerts.list(),
    refetchInterval: 20_000,
  });
  const { data: incidents } = useQuery({
    queryKey: ["incidents", "open"],
    queryFn: () => api.infra.incidents({ status: "open" }),
    refetchInterval: 30_000,
  });
  const { data: agents } = useQuery({
    queryKey: ["agents", "all"],
    queryFn: () => api.agents.list(),
    refetchInterval: 60_000,
  });
  const { data: runs } = useQuery({
    queryKey: ["workflow-runs", "home"],
    queryFn: () => api.workflows.runs(),
    refetchInterval: 15_000,
  });
  const { data: events } = useQuery({
    queryKey: ["events", "24h"],
    queryFn: () => api.events.list({ since_hours: 24, limit: 200 }),
    refetchInterval: 30_000,
  });
  const { data: briefings } = useQuery({
    queryKey: ["briefings", "infra"],
    queryFn: () => api.briefings.list("infra"),
    refetchInterval: 5 * 60_000,
  });

  const openAlerts = (alerts ?? []).filter((a) => a.status === "open");
  const critical = openAlerts.filter((a) => a.severity === "critical").length;
  const running = (runs ?? []).filter(
    (r) => r.status === "running" || r.status === "waiting_for_approval"
  ).length;
  const startOfToday = new Date();
  startOfToday.setHours(0, 0, 0, 0);
  const succeededToday = (runs ?? []).filter(
    (r) =>
      r.status === "succeeded" &&
      r.finished_at !== null &&
      new Date(r.finished_at).getTime() >= startOfToday.getTime()
  ).length;

  // Activity counts the same alerts the greeting and briefing talk about,
  // plus raw events, so the tile can't say "0" while alerts are firing.
  const dayAgo = Date.now() - 24 * 60 * 60 * 1000;
  const alerts24h = (alerts ?? []).filter(
    (a) => new Date(a.last_seen_at ?? a.created_at).getTime() >= dayAgo
  );
  const activityLoaded = alerts !== undefined && events !== undefined;
  const activityTotal = alerts24h.length + (events?.length ?? 0);
  const buckets = bucketize([
    ...(events ?? []).map((e) => e.occurred_at),
    ...alerts24h.map((a) => a.last_seen_at ?? a.created_at),
  ]);

  const plural = (n: number, word: string) => `${n} ${word}${n === 1 ? "" : "s"}`;
  const incidentsNote =
    incidents && incidents.length > 0 ? ` · ${plural(incidents.length, "incident")}` : "";

  return (
    <div className="space-y-6 max-w-[1400px]">
      <GreetingHero
        critical={critical}
        open={openAlerts.length}
        loaded={!alertsLoading && alerts !== undefined}
      />

      {/* The daily briefing: its first sentence as the headline, the
       *  rest folded, sections as tiles. Generated by an agent. */}
      <HeroBriefing channel="infra" />

      {/* One swipeable row on a phone, a grid from sm up. */}
      <div className="-mx-4 px-4 flex gap-3 overflow-x-auto snap-x snap-mandatory pb-1 sm:mx-0 sm:px-0 sm:pb-0 sm:grid sm:grid-cols-2 lg:grid-cols-3 sm:gap-4 sm:overflow-visible [&>*]:min-w-[72%] [&>*]:snap-start sm:[&>*]:min-w-0">
        <SummaryTile
          href="/alerts?tab=open"
          icon={AlertTriangle}
          // Windows in the labels: these are live counts, the briefing's
          // figures cover its own window, so the two needn't match.
          label="Open now"
          value={alerts ? openAlerts.length : "—"}
          hint={
            alerts === undefined
              ? "Loading…"
              : (critical > 0 ? `${critical} critical` : "None critical") +
                (incidentsNote ? `${incidentsNote} open` : "")
          }
          intent={alerts === undefined ? "neutral" : critical > 0 ? "negative" : "positive"}
        />
        <SummaryTile
          href="/alerts"
          icon={Activity}
          label="Seen in last 24h"
          value={activityLoaded ? activityTotal : "—"}
          hint={
            activityLoaded
              ? `${plural(alerts24h.length, "distinct alert")} · ${plural(events?.length ?? 0, "event")}`
              : "Loading…"
          }
          spark={activityLoaded ? buckets : undefined}
        />
        <SummaryTile
          href="/workflows"
          icon={Workflow}
          label="Workflows running"
          value={runs ? running : "—"}
          hint={runs ? `${succeededToday} completed today` : "Loading…"}
        />
        <SummaryTile
          href="/agents"
          icon={Bot}
          label="Active agents"
          value={agents?.length ?? "—"}
          hint={agents ? "Workforce online" : "Loading…"}
        />
        <SummaryTile
          href="/reports"
          icon={FileText}
          label="Briefings on file"
          value={briefings?.length ?? "—"}
          hint={briefings ? "All archived runs" : "Loading…"}
        />
      </div>
    </div>
  );
}

/**
 * Coarse 6-bucket histogram of alert + event counts over the last 24h. Used as
 * the sparkline data on the Operational activity tile.
 */
function bucketize(timestamps: string[]): number[] {
  const N = 6;
  const buckets = Array(N).fill(0);
  const cutoff = Date.now() - 24 * 60 * 60 * 1000;
  for (const ts of timestamps) {
    const t = new Date(ts).getTime();
    if (t < cutoff) continue;
    const idx = Math.min(N - 1, Math.floor(((t - cutoff) / (24 * 60 * 60 * 1000)) * N));
    buckets[idx] += 1;
  }
  return buckets;
}
